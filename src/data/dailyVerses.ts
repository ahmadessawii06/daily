/**
 * Returns a consistent daily verse for the given date.
 * Uses a deterministic hash based on the date string (YYYY-MM-DD),
 * ensuring the verse remains steady throughout the entire day and
 * is completely decoupled from task progress completion.
 */
export function getDailyVerse(dateStr?: string): DailyVerse {
  const date = dateStr && dateStr.trim().length > 0 ? dateStr.trim() : new Date().toISOString().slice(0, 10);
  let hash = 0;
  for (let i = 0; i < date.length; i++) {
    hash = (hash << 5) - hash + date.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % DAILY_VERSES.length;
  return DAILY_VERSES[index];
}
